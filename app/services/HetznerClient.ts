/**
 * Minimal Hetzner Cloud API client. No third-party dependencies:
 * it uses Node's built-in fetch.
 *
 * Unlike Linode, EVERY Hetzner endpoint needs a project token, including the
 * catalog ones (locations, server types, images). So the catalog methods are
 * instance methods here, not static.
 *
 * Differences from LinodeClient that the provision job must respect:
 *   - Labels are a key/value map, not a tag array.
 *   - ssh_keys must be registered key resources, so authorized keys are
 *     injected with cloud-init instead (this also keeps Hetzner's generated
 *     root password, which is only returned when no ssh_keys are passed).
 *   - The root password is generated BY Hetzner and returned from createInstance.
 *   - Prices are EUR, gross (incl. VAT).
 */

const API_BASE = "https://api.hetzner.cloud/v1";
const TIMEOUT_MS = 20_000;
const PER_PAGE = 50;

/** Images the provisioning scripts support (apt-based, x86). */
const SUPPORTED_IMAGES: Record<string, string> = {
    "ubuntu-24.04": "Ubuntu 24.04 LTS",
    "ubuntu-22.04": "Ubuntu 22.04 LTS",
    "debian-12": "Debian 12",
};

export interface HetznerLocation {
    id: string;
    label: string;
    country: string;
}

export interface HetznerPlan {
    id: string;
    label: string;
    class: string;
    memory_mb: number;
    vcpus: number;
    disk_gb: number;
    monthly: number;
    hourly: number;
    currency: "EUR";
}

export interface HetznerImage {
    id: string;
    label: string;
}

export interface HetznerInstance {
    id: number;
    label: string;
    status: string;
    region: string;
    type: string;
    ipv4: string[];
    labels: Record<string, string>;
}

export interface CreateHetznerInstanceInput {
    region: string;
    type: string;
    image: string;
    label: string;
    authorizedKeys: string[];
    labels?: Record<string, string>;
}

export class HetznerError extends Error {
    status: number;
    code: string;

    constructor(message: string, status: number, code = "") {
        super(message);
        this.name = "HetznerError";
        this.status = status;
        this.code = code;
    }
}

interface RawServer {
    id: number;
    name: string;
    status: string;
    public_net?: { ipv4?: { ip?: string } | null };
    server_type?: { name: string };
    datacenter?: { location?: { name: string } };
    labels?: Record<string, string>;
}

function toInstance(raw: RawServer): HetznerInstance {
    const ip = raw.public_net?.ipv4?.ip;
    return {
        id: raw.id,
        label: raw.name,
        status: raw.status,
        region: raw.datacenter?.location?.name ?? "",
        type: raw.server_type?.name ?? "",
        ipv4: ip ? [ip] : [],
        labels: raw.labels ?? {},
    };
}

/** Cloud-init that puts the keys on root. JSON strings are valid YAML scalars. */
function buildUserData(keys: string[]): string | undefined {
    if (keys.length === 0) return undefined;
    const lines = ["#cloud-config", "ssh_authorized_keys:"];
    for (const key of keys) lines.push(`  - ${JSON.stringify(key.trim())}`);
    return lines.join("\n") + "\n";
}

/**
 * Says WHY a fetch failed (timeout, DNS, no route...) without ever including
 * the request details, which carry the token. Only the error name and the
 * system error code are used.
 */
function describeNetworkFailure(error: unknown): string {
    const err = error as { name?: string; code?: string; cause?: { code?: string } } | null;

    if (err?.name === "TimeoutError" || err?.name === "AbortError") {
        return "timed out";
    }

    const code = err?.cause?.code ?? err?.code;
    return code ? String(code) : "network error";
}

async function request<T>(
    method: string,
    path: string,
    token: string,
    body?: unknown,
): Promise<T> {
    const headers: Record<string, string> = {
        Accept: "application/json",
        Authorization: `Bearer ${token}`,
    };
    if (body !== undefined) headers["Content-Type"] = "application/json";

    let response: Response;
    try {
        response = await fetch(`${API_BASE}${path}`, {
            method,
            headers,
            body: body === undefined ? undefined : JSON.stringify(body),
            signal: AbortSignal.timeout(TIMEOUT_MS),
        });
    } catch (error) {
        // Never include the request details here: they carry the token.
        throw new HetznerError(
            `Could not reach the Hetzner API (${describeNetworkFailure(error)}).`,
            0,
        );
    }

    const text = await response.text();
    let json: unknown = null;
    try {
        json = text ? JSON.parse(text) : null;
    } catch {
        // Non-JSON body: fall through with json = null.
    }

    if (!response.ok) {
        const err = (json as { error?: { code?: string; message?: string } } | null)?.error;
        throw new HetznerError(
            err?.message ?? `Hetzner API error (${response.status})`,
            response.status,
            err?.code ?? "",
        );
    }

    return json as T;
}

export class HetznerClient {
    private token: string;

    constructor(token: string) {
        this.token = token;
    }

    /**
     * Throws HetznerError (401/403) if the token is invalid.
     * A Read-only token passes this check and only fails when creating a server.
     */
    async verify(): Promise<void> {
        await request("GET", "/servers?per_page=1", this.token);
    }

    /** Follows meta.pagination until every page of `key` has been collected. */
    private async all<T>(path: string, key: string): Promise<T[]> {
        const out: T[] = [];
        const sep = path.includes("?") ? "&" : "?";
        let page: number | null = 1;

        while (page) {
            const res: Record<string, unknown> = await request(
                "GET",
                `${path}${sep}per_page=${PER_PAGE}&page=${page}`,
                this.token,
            );
            out.push(...((res[key] as T[]) ?? []));
            page = (res.meta as { pagination?: { next_page: number | null } } | undefined)
                ?.pagination?.next_page ?? null;
        }

        return out;
    }

    /** Hetzner generates the root password; it is returned only here, once. */
    async createInstance(
        input: CreateHetznerInstanceInput,
    ): Promise<{ instance: HetznerInstance; rootPassword: string | null }> {
        const res = await request<{ server: RawServer; root_password: string | null }>(
            "POST",
            "/servers",
            this.token,
            {
                name: input.label,
                server_type: input.type,
                image: input.image,
                location: input.region,
                user_data: buildUserData(input.authorizedKeys),
                labels: input.labels ?? {},
                start_after_create: true,
                public_net: { enable_ipv4: true, enable_ipv6: true },
            },
        );
        return { instance: toInstance(res.server), rootPassword: res.root_password ?? null };
    }

    async getInstance(id: number): Promise<HetznerInstance> {
        const res = await request<{ server: RawServer }>("GET", `/servers/${id}`, this.token);
        return toInstance(res.server);
    }

    /** Finds an instance by a label selector such as "tylix-provision=42", or null. */
    async findByLabel(selector: string): Promise<HetznerInstance | null> {
        const res = await request<{ servers: RawServer[] }>(
            "GET",
            `/servers?label_selector=${encodeURIComponent(selector)}&per_page=1`,
            this.token,
        );
        return res.servers.length > 0 ? toInstance(res.servers[0]) : null;
    }

    async deleteInstance(id: number): Promise<void> {
        try {
            await request("DELETE", `/servers/${id}`, this.token);
        } catch (error) {
            // Already gone is the outcome we wanted.
            if (error instanceof HetznerError && error.status === 404) return;
            throw error;
        }
    }

    // ---- Catalog (needs a token on Hetzner) ----

    async regions(): Promise<HetznerLocation[]> {
        const rows = await this.all<{ name: string; city: string; country: string }>(
            "/locations",
            "locations",
        );
        return rows
            .map((l) => ({ id: l.name, label: `${l.city} (${l.name})`, country: l.country }))
            .sort((a, b) => a.label.localeCompare(b.label));
    }

    async plans(region?: string): Promise<HetznerPlan[]> {
        const rows = await this.all<{
            name: string;
            cores: number;
            memory: number;
            disk: number;
            cpu_type: string;
            architecture: string;
            deprecated?: boolean;
            deprecation?: unknown;
            prices: {
                location: string;
                price_hourly: { gross: string };
                price_monthly: { gross: string };
            }[];
        }>("/server_types", "server_types");

        const plans: HetznerPlan[] = [];

        for (const t of rows) {
            if (t.architecture !== "x86" || t.deprecated || t.deprecation) continue;

            const price = region
                ? t.prices.find((p) => p.location === region)
                : t.prices[0];

            // No price for this location means the plan isn't offered there.
            if (!price) continue;

            plans.push({
                id: t.name,
                label: t.name.toUpperCase(),
                class: t.cpu_type, // "shared" or "dedicated"
                memory_mb: Math.round(t.memory * 1024),
                vcpus: t.cores,
                disk_gb: t.disk,
                monthly: Number(price.price_monthly.gross),
                hourly: Number(price.price_hourly.gross),
                currency: "EUR",
            });
        }

        return plans.sort((a, b) => a.monthly - b.monthly);
    }

    async images(): Promise<HetznerImage[]> {
        const rows = await this.all<{ name: string | null; deprecated?: string | null }>(
            "/images?type=system&status=available&architecture=x86",
            "images",
        );

        const available = new Set(
            rows.filter((i) => i.name && !i.deprecated).map((i) => i.name as string),
        );

        return Object.keys(SUPPORTED_IMAGES)
            .filter((id) => available.has(id))
            .map((id) => ({ id, label: SUPPORTED_IMAGES[id] }));
    }
}